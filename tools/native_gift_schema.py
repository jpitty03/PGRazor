"""Validate neutral gift metadata and generate native code/type constants."""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'pgrazor/native/schema/gifts.json'
OUTPUT = ROOT / 'pgrazor/native/shared_gift_code.h'

def unique_pairs(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError('Duplicate JSON key: ' + key)
        result[key] = value
    return result

def parse(source):
    value = json.loads(source, object_pairs_hook=unique_pairs)
    if not isinstance(value, dict) or set(value) != {'version', 'types', 'codes', 'open_sequence'}:
        raise ValueError('Unexpected gift schema fields')
    if type(value['version']) is not int or value['version'] != 1:
        raise ValueError('Unsupported gift schema version')
    if not isinstance(value['types'], dict) or not value['types'] or not isinstance(value['codes'], dict) or not value['codes']:
        raise ValueError('Expected nonempty gift type and code mappings')
    for key, name in value['types'].items():
        if not re.fullmatch(r'(?:0|[1-9][0-9]*)', key) or not isinstance(name, str) or not re.fullmatch(r'[A-Za-z0-9_.`+]+', name):
            raise ValueError('Invalid gift type mapping')
    for key, code in value['codes'].items():
        if not re.fullmatch(r'(?:0|[1-9][0-9]*)\.[A-Za-z0-9_]+', key):
            raise ValueError('Invalid gift code key')
        validate_code(code)
    validate_code(value['open_sequence'])
    return {'GIFT_TYPES': value['types'], 'GIFT_CODE': value['codes'], 'GIFT_OPEN_SEQUENCE_CODE': value['open_sequence']}


def validate_code(value):
    if not isinstance(value, list) or len(value) != 2:
        raise ValueError('Expected [RVA,hex]')
    rva, text = value
    if type(rva) is not int or not 0 < rva <= (1 << 53) - 1 or rva % 4:
        raise ValueError('Invalid aligned safe-integer RVA')
    if not isinstance(text, str) or not re.fullmatch(r'(?:[0-9a-fA-F]{2}){1,80}', text):
        raise ValueError('Invalid/overlong code bytes')


def row(key, value):
    rva, text = value
    data = bytes.fromhex(text)
    return '  {' + json.dumps(key) + ',0x%xULL,{' % rva + ','.join('0x%02x' % b for b in data) + '},%du}' % len(data)


def render(values):
    digest = hashlib.sha256(json.dumps(values, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    lines = ['#pragma once', '#include <stdint.h>', '#include <stddef.h>', '',
             '// Generated by tools/native_gift_schema.py from native/schema/gifts.json.',
             '// Versioned native metadata constants; do not hand-edit.',
             '// Effective constants SHA-256: ' + digest,
             'namespace pgr_shared_gift {',
             'struct Code {const char *key; uint64_t rva; unsigned char bytes[80]; uint32_t length;};',
             'inline constexpr Code kCodes[] = {']
    lines += [row(key, value) + ',' for key, value in sorted(values['GIFT_CODE'].items())]
    lines += ['};', 'inline constexpr size_t kCodeCount=sizeof(kCodes)/sizeof(kCodes[0]);',
              'inline constexpr Code kSequence=' + row('GIFT_OPEN_SEQUENCE_CODE', values['GIFT_OPEN_SEQUENCE_CODE']).strip() + ';',
              'struct Type {const char *id; const char *canonical;};', 'inline constexpr Type kTypes[] = {']
    lines += ['  {' + json.dumps(key) + ',' + json.dumps(value) + '},' for key, value in sorted(values['GIFT_TYPES'].items(), key=lambda item: int(item[0]))]
    lines += ['};', 'inline constexpr size_t kTypeCount=sizeof(kTypes)/sizeof(kTypes[0]);',
              '} // namespace pgr_shared_gift', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    values = parse(SOURCE.read_text(encoding='utf-8'))
    generated = render(values)
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding='utf-8') != generated:
            raise SystemExit('Stale generated gift header: run tools/native_gift_schema.py')
    else:
        OUTPUT.write_text(generated, encoding='utf-8', newline='\n')
    print(('Checked' if args.check else 'Generated') + ' gift schema: ' + str(len(values['GIFT_CODE'])) + ' codes, ' + str(len(values['GIFT_TYPES'])) + ' types; header SHA-256 ' + hashlib.sha256(generated.encode()).hexdigest())


if __name__ == '__main__':
    main()
