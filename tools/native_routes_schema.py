"""Validate neutral Routes metadata and generate its ordered native descriptors."""
from pathlib import Path
import argparse
import json
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'pgrazor/native/schema/routes.json'
OUTPUT = ROOT / 'pgrazor/native/routes_schema.h'

class SchemaError(ValueError):
    pass

def unique_pairs(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise SchemaError('Duplicate JSON key: ' + key)
        result[key] = value
    return result

def shape(value, keys):
    if not isinstance(value, dict) or set(value) != set(keys):
        raise SchemaError('Unexpected schema object fields')

def text(value, nullable=False):
    if value is None and nullable:
        return
    if not isinstance(value, str) or not value or len(value) > 1024 or any(ord(c) < 32 for c in value):
        raise SchemaError('Invalid metadata string')

def parse(source):
    try:
        value = json.loads(source, object_pairs_hook=unique_pairs)
    except json.JSONDecodeError as error:
        raise SchemaError('Invalid JSON') from error
    shape(value, ('version', 'classes', 'fields', 'methods'))
    if type(value['version']) is not int or value['version'] != 1:
        raise SchemaError('Unsupported schema version')
    for key in ('classes', 'fields', 'methods'):
        if not isinstance(value[key], list) or not value[key]:
            raise SchemaError('Expected nonempty ordered ' + key)
    classes, fields, methods = {}, [], {}
    def key_name(key):
        text(key)
        if not re.fullmatch(r'[A-Za-z_$][A-Za-z0-9_$]*', key):
            raise SchemaError('Invalid descriptor key')
    for item in value['classes']:
        shape(item, ('key', 'namespace', 'name', 'canonical'))
        key = item['key']; key_name(key)
        for name in ('namespace', 'name', 'canonical'):
            text(item[name])
        if key in classes or item['canonical'] != item['namespace'] + '.' + item['name']:
            raise SchemaError('Duplicate class key or inconsistent canonical name')
        classes[key] = (item['namespace'], item['name'], item['canonical'])
    indices = {key: index for index, key in enumerate(classes)}
    seen_fields = set()
    for item in value['fields']:
        shape(item, ('owner', 'name', 'offset', 'kind', 'type', 'size'))
        text(item['owner']); text(item['name']); text(item['type'], True)
        identity = (item['owner'], item['name'])
        if item['owner'] not in classes or identity in seen_fields:
            raise SchemaError('Missing field owner or duplicate field')
        seen_fields.add(identity)
        if type(item['offset']) is not int or not 0 <= item['offset'] <= 0xffffffffffffffff:
            raise SchemaError('Field offset outside uint64')
        if type(item['kind']) is not int or type(item['size']) is not int:
            raise SchemaError('Field kind and size must be integers')
        if (item['kind'], item['type'], item['size']) not in (
            (1, None, 0), (1, 'System.String', 0), (2, 'System.Boolean', 1),
            (2, 'System.Int64', 8), (2, 'System.Double', 8), (3, None, 4)):
            raise SchemaError('Unsupported field type/kind/size combination')
        fields.append(tuple(item[key] for key in ('owner', 'name', 'offset', 'kind', 'type', 'size')))
    for item in value['methods']:
        shape(item, ('key', 'owner', 'name', 'return', 'params'))
        key = item['key']; key_name(key)
        text(item['owner']); text(item['name']); text(item['return'], True)
        if key in methods or item['owner'] not in classes:
            raise SchemaError('Duplicate method key or missing owner')
        params = item['params']
        if not isinstance(params, list) or len(params) > 1:
            raise SchemaError('Only zero/one managed parameter supported')
        for param in params:
            text(param)
        methods[key] = (item['owner'], item['name'], item['return'], len(params), params[0] if params else None)
    return classes, indices, fields, methods


def render(source):
    classes, indices, fields, methods = parse(source)
    literal = lambda value: 'nullptr' if value is None else json.dumps(value, ensure_ascii=True)
    lines = [
        '// Generated by tools/native_routes_schema.py; do not hand-edit.',
        '// Source: pgrazor/native/schema/routes.json (versioned metadata descriptors).',
        '// Indices preserve declaration order; no inferred signatures or runtime behavior.',
        '#pragma once', '#include <stddef.h>', '#include <stdint.h>', '',
        'namespace pgr_routes_schema {',
        'struct ClassSpec {const char *key,*name_space,*name,*canonical;};',
        'struct FieldSpec {uint32_t owner;const char *name;uint64_t offset;uint32_t kind;const char *type_name;uint32_t value_size;};',
        'struct MethodSpec {const char *key;uint32_t owner;const char *name,*return_type;uint32_t param_count;const char *param0;};',
        '// Field kinds: ANY=0, REF=1, VALUE=2, ENUM_I32=3 (runtime_metadata.h).',
        'inline constexpr ClassSpec kClasses[] = {',
    ]
    for key, (name_space, name, canonical) in classes.items():
        lines.append('  {' + ','.join(map(literal, (key, name_space, name, canonical))) + '}, // ' + str(indices[key]))
    lines += ['};', 'inline constexpr size_t kClassCount=sizeof(kClasses)/sizeof(kClasses[0]);', '',
              'inline constexpr FieldSpec kFields[] = {']
    for index, (key, name, offset, kind, type_name, value_size) in enumerate(fields):
        lines.append(f'  {{{indices[key]}u,{literal(name)},0x{offset:x}ULL,{kind}u,{literal(type_name)},{value_size}u}}, // {index}: {key}.{name}')
    lines += ['};', 'inline constexpr size_t kFieldCount=sizeof(kFields)/sizeof(kFields[0]);', '',
              'inline constexpr MethodSpec kMethods[] = {']
    for index, (key, (owner, name, result, count, param0)) in enumerate(methods.items()):
        lines.append(f'  {{{literal(key)},{indices[owner]}u,{literal(name)},{literal(result)},{count}u,{literal(param0)}}}, // {index}')
    lines += ['};', 'inline constexpr size_t kMethodCount=sizeof(kMethods)/sizeof(kMethods[0]);',
              '} // namespace pgr_routes_schema', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if checked-in header differs from exact generated descriptors')
    args = parser.parse_args()
    try:
        source = SOURCE.read_text(encoding='utf-8')
        expected = render(source)
        classes, _, fields, methods = parse(source)
        if args.check:
            if not OUTPUT.is_file() or OUTPUT.read_bytes() != expected.encode('utf-8'):
                print('Routes schema mismatch: run python -B tools/native_routes_schema.py', file=sys.stderr)
                return 1
        else:
            OUTPUT.write_bytes(expected.encode('utf-8'))
        print(f'Routes schema {"matches" if args.check else "generated"}: {len(classes)} classes, {len(fields)} fields, {len(methods)} methods')
        return 0
    except (OSError, SchemaError) as failure:
        print('Routes schema rejected: ' + str(failure), file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(main())
