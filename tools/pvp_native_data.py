"""Generate deterministic native PvP tables from the original patch's pinned snapshot."""
import argparse,json
from pathlib import Path
def generate(root):
 data=json.loads((root/'pgrazor/assets/pvp/data.json').read_text(encoding='utf8'))
 rows=data['species'];cpm=data['cpm'];assert len(cpm)>=99
 keys=[]
 for key,index in data['keys'].items():
  parts=key.split(':');keys.append((int(parts[0]),int(parts[1]) if len(parts)>1 else -1,index))
 assert all(0<=index<len(rows) for _,_,index in keys)
 edges=[];out=['// Generated by tools/pvp_native_data.py; see assets/pvp/LICENSE-PvPoke.txt.', '#pragma once','namespace pgr_pvp {','struct Species {const char *name; int attack,defense,stamina,floor,start,edge,count;};','struct Key {int dex,form,index;};','static const Species species[]={']
 for name,a,d,s,floor,start,evos in rows:
  assert '<' not in name and '>' not in name and 0<=floor<=15 and all(0<=e<len(rows) for e in evos)
  out.append('{'+json.dumps(name,ensure_ascii=False)+','+','.join(map(str,[a,d,s,floor,round((start-1)*2),len(edges),len(evos)]))+'},');edges.extend(evos)
 out+=['};','static const int edges[]={'+','.join(map(str,edges))+'};','static const Key keys[]={']
 out+=['{'+','.join(map(str,key))+'},' for key in sorted(keys)]
 out+=['};','static const double cpm[]={'+','.join(repr(v) for v in cpm[:99])+'};','} // namespace pgr_pvp','']
 return '\n'.join(out)
def main():
 parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
 root=Path(__file__).resolve().parent.parent;target=root/'pgrazor/native/pvp_data.h';text=generate(root)
 if args.check:
  if not target.exists() or target.read_text(encoding='utf8')!=text:raise SystemExit('Native PvP snapshot is stale')
  print('PASS: native PvP data matches the pinned snapshot')
 else:target.write_text(text,encoding='utf8',newline='\n')
if __name__=='__main__':main()
