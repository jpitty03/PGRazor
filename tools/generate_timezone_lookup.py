"""Generate the offline Java lookup from the pinned CC0 tz-lookup source.

No downloads or JS execution. Original inputs/license live in pgrazor/vendor/tz-lookup.
"""
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def generate():
    vendor = ROOT / 'pgrazor/vendor/tz-lookup'
    provenance = json.loads((vendor / 'provenance.json').read_text())
    source = (vendor / 'tz.js').read_bytes()
    if hashlib.sha256(source).hexdigest() != provenance['sha256']['tz.js']:
        raise ValueError('Pinned timezone source hash mismatch')
    match = re.search(r'var X=("(?:[^"\\]|\\.)*"),T=(\[[^\]]+\])', source.decode())
    if not match:
        raise ValueError('Unsupported upstream timezone encoding')
    data, zones = json.loads(match[1]), json.loads(match[2])
    # Split so no constant exceeds the JVM's 65535-byte UTF-8 limit.
    chunks = '\n'.join('        .append(' + json.dumps(data[i:i+8000]) + ')'
                       for i in range(0, len(data), 8000))
    zone_lines = ',\n'.join('        ' + json.dumps(zone) for zone in zones)
    return '''package dev.pgrazor;

/** Offline, approximate geographic time-zone lookup. Generated by tools/generate_timezone_lookup.py.
 * CC0 tz-lookup 11.8.0; provenance/license in pgrazor/vendor/tz-lookup.
 * Compressed boundaries can be approximate near time-zone borders.
 */
final class TimeZoneLookup {
    private TimeZoneLookup() { }
    private static final String DATA = new StringBuilder()
''' + chunks + '''.toString();
    private static final String[] ZONES = {
''' + zone_lines + '''
    };

    static String zoneId(double latitude, double longitude) {
        if (!(latitude >= -90 && latitude <= 90 && longitude >= -180 && longitude <= 180))
            throw new IllegalArgumentException("Invalid coordinates");
        if (latitude >= 90) return "Etc/GMT";
        int node = -1;
        double x = (180 + longitude) * 48 / 360.00000000000006;
        double y = (90 - latitude) * 24 / 180.00000000000003;
        int u = (int)x, v = (int)y;
        int index = value(v * 96 + u * 2);
        while (index + ZONES.length < 3136) {
            node += index + 1;
            x = ((x - u) * 2) % 2;
            y = ((y - v) * 2) % 2;
            u = (int)x; v = (int)y;
            index = value(node * 8 + v * 4 + u * 2 + 2304);
        }
        return ZONES[index + ZONES.length - 3136];
    }

    private static int value(int index) {
        return DATA.charAt(index) * 56 + DATA.charAt(index + 1) - 1995;
    }
}
'''


if __name__ == '__main__':
    target = ROOT / 'pgrazor/src/dev/pgrazor/TimeZoneLookup.java'
    target.write_text(generate(), encoding='utf-8')
    print('Generated', target.relative_to(ROOT))
