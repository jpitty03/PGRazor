"""Generate the offline species categories from a pinned Pokemon GO Game Master.

Download latest/latest.json from a specific PokeMiners/game_masters commit, then:
  python pgrazor/generate_pokemon_categories.py <download.json> --commit <40-char SHA>

This is a species catalog, not an event/release/raid-availability list. A species
with any Mega override belongs to Mega-capable, even if its Mega is unreleased.
Primal overrides are kept separate. All forms collapse to their National Dex ID.
Evolution stages count from the first species, including babies; Mega/Primal
forms are not an extra stage. Stage 2 means evolved once, Stage 3 means twice.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent
GROUPS = ('LEGENDARY', 'MYTHICAL', 'ULTRA_BEAST', 'MEGA', 'PRIMAL', 'STAGE_2', 'STAGE_3')
CLASSES = {'POKEMON_CLASS_LEGENDARY': 'LEGENDARY',
           'POKEMON_CLASS_MYTHIC': 'MYTHICAL',
           'POKEMON_CLASS_ULTRA_BEAST': 'ULTRA_BEAST'}
MEGA = {'TEMP_EVOLUTION_MEGA', 'TEMP_EVOLUTION_MEGA_X', 'TEMP_EVOLUTION_MEGA_Y'}


def evolution_stages(rows):
    """Collapse form records, then follow immediate parent species with strict graph validation."""
    symbols, parents = {}, {}
    for row in rows:
        pokemon = row.get('data', {}).get('pokemonSettings')
        if not pokemon:
            continue
        dex = int(row['templateId'][1:5])
        name = pokemon['pokemonId']
        if name in symbols and symbols[name] != dex:
            raise ValueError('Species symbol maps to multiple Dex IDs: ' + name)
        symbols[name] = dex
        parents.setdefault(name, set())
        parent = pokemon.get('parentPokemonId')
        if parent:
            parents[name].add(parent)
    stages, visiting = {}, set()

    def stage(name):
        if name in stages:
            return stages[name]
        if name not in symbols:
            raise ValueError('Unknown parent species: ' + name)
        if name in visiting:
            raise ValueError('Evolution cycle: ' + name)
        if len(parents[name]) > 1:
            raise ValueError('Conflicting parent species: ' + name)
        visiting.add(name)
        value = 1 + max((stage(parent) for parent in parents[name]), default=0)
        visiting.remove(name)
        if value > 3:
            raise ValueError('Unsupported evolution depth: ' + name)
        stages[name] = value
        return value

    return {dex: stage(name) for name, dex in symbols.items()}


def categories(rows):
    groups = {key: set() for key in GROUPS}
    for row in rows:
        data = row.get('data', {})
        pokemon = data.get('pokemonSettings')
        if not pokemon:
            continue
        template = row.get('templateId', '')
        match = re.fullmatch(r'V(\d{4})_POKEMON_.+', template)
        if not match:
            raise ValueError('Unrecognized Pokemon template: ' + template)
        dex = int(match[1])
        if not 1 <= dex <= 2000:
            raise ValueError('Unsupported Dex ID: ' + str(dex))
        kind = pokemon.get('pokemonClass')
        if kind in CLASSES:
            groups[CLASSES[kind]].add(dex)
        elif kind not in (None, 'POKEMON_CLASS_NORMAL'):
            raise ValueError('Unknown Pokemon class: ' + str(kind))
        for override in pokemon.get('tempEvoOverrides', []):
            evolution = override.get('tempEvoId')
            if evolution in MEGA:
                groups['MEGA'].add(dex)
            elif evolution == 'TEMP_EVOLUTION_PRIMAL':
                groups['PRIMAL'].add(dex)
            elif evolution is not None:
                raise ValueError('Unknown temporary evolution: ' + str(evolution))
    for dex, stage in evolution_stages(rows).items():
        if stage in (2, 3):
            groups['STAGE_' + str(stage)].add(dex)
    return groups


def render(groups, commit, digest):
    arrays = []
    for group in GROUPS:
        ids = sorted(groups[group])
        lines = [', '.join(map(str, ids[i:i+16])) for i in range(0, len(ids), 16)]
        arrays.append('    private static final int[] ' + group + '_IDS = {\n        '
                      + ',\n        '.join(lines) + '\n    };')
    return '''package dev.pgrazor;

/**
 * Generated by generate_pokemon_categories.py; do not edit the ID lists by hand.
 * Source: https://github.com/PokeMiners/game_masters/blob/COMMIT/latest/latest.json
 * Source SHA256: DIGEST
 * Species categories include configured forms, not current raid or release availability.
 * Mega and Primal are independent; a species can also be Legendary or Mythical.
 * Evolution stages include babies and exclude temporary Mega/Primal forms.
 */
final class PokemonCategories {
    private PokemonCategories() {}
    static final int ALL = 0, LEGENDARY = 1, MYTHICAL = 2, ULTRA_BEAST = 3,
        MEGA = 4, PRIMAL = 5, STAGE_2 = 6, STAGE_3 = 7, SELECTED = 8;
    static final String[] LABELS = {"All Pokemon", "Legendary", "Mythical", "Ultra Beasts",
        "Mega-capable", "Primal-capable", "Stage 2 (e.g. Ivysaur)", "Stage 3 (e.g. Venusaur)", "Selected"};
ARRAYS

    static boolean matches(int category, int dexId, boolean selected) {
        if (dexId < 1 || dexId > 2000) return false;
        switch (category) {
            case ALL: return true;
            case SELECTED: return selected;
            case LEGENDARY: return contains(LEGENDARY_IDS, dexId);
            case MYTHICAL: return contains(MYTHICAL_IDS, dexId);
            case ULTRA_BEAST: return contains(ULTRA_BEAST_IDS, dexId);
            case MEGA: return contains(MEGA_IDS, dexId);
            case PRIMAL: return contains(PRIMAL_IDS, dexId);
            case STAGE_2: return contains(STAGE_2_IDS, dexId);
            case STAGE_3: return contains(STAGE_3_IDS, dexId);
            default: return false;
        }
    }

    private static boolean contains(int[] ids, int id) {
        return java.util.Arrays.binarySearch(ids, id) >= 0;
    }
}
'''.replace('COMMIT', commit).replace('DIGEST', digest).replace('ARRAYS', '\n'.join(arrays))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('--commit', required=True)
    args = parser.parse_args()
    if not re.fullmatch('[a-f0-9]{40}', args.commit):
        parser.error('--commit must be a full Git commit SHA')
    raw = args.source.read_bytes()
    groups = categories(json.loads(raw))
    if any(not ids for ids in groups.values()):
        raise ValueError('Incomplete Game Master: one or more category groups are empty')
    target = ROOT/'src/dev/pgrazor/PokemonCategories.java'
    target.write_text(render(groups, args.commit, hashlib.sha256(raw).hexdigest()), encoding='utf-8')
    print({key: len(ids) for key, ids in groups.items()})


if __name__ == '__main__':
    main()
