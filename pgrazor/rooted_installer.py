"""Builds the standalone PGRazor Root installer APK (package dev.pgrazor.root).

The installer carries the Zygisk module zip in its assets and installs it with the phone's root
manager (Magisk 27+, KernelSU or APatch). It is the rooted counterpart of the patched APK that
nonroot.py produces, and is signed with the same local/release key via build.signing_args().

This module only assembles the APK. rooted.package() builds the module zip, then calls
build_installer(module_zip, target, version, folder) with it; see build_installer's docstring for
the exact integration call. The installer's Java UI and manifest live under pgrazor/root-installer/;
only the per-build InstallerConfig.java (game/version/certificate constants) is generated here, the
same way build.py generates BuildVersion.java.
"""
import argparse
import json
import re
import uuid
import zipfile
from pathlib import Path

import build
import nonroot

ROOT = Path(__file__).resolve().parent
INSTALLER_DIR = ROOT / 'root-installer'
PACKAGE = 'dev.pgrazor.root'
# Classes that must exist after compilation; a missing one means javac silently skipped sources.
EXPECTED_CLASSES = ('InstallerActivity', 'RestartActivity', 'RootShell', 'RootStatus', 'InstallerConfig')


def installer_version_code(version):
    """versionCode for the installer APK, derived from the PGRazor version (vMAJOR.MINOR.PATCH).

    Kept local rather than imported from rooted.py so the build helper has no import dependency on
    the packager that calls it; the formula matches rooted.version_code.
    """
    match = re.fullmatch(r'v?([0-9]+)\.([0-9]+)\.([0-9]+)(?:-[A-Za-z0-9]+(?:[.-][A-Za-z0-9]+)*)?', str(version))
    if not match:
        raise ValueError('Invalid PGRazor version ' + str(version))
    major, minor, patch = map(int, match.groups())
    code = major * 1000000 + minor * 1000 + patch
    if minor >= 1000 or patch >= 1000 or not 0 < code <= 2100000000:
        raise ValueError('PGRazor version is outside Android versionCode limits')
    return code


def _config_source(target, version, module_asset):
    """Generates InstallerConfig.java: the game target, PGRazor version and the trusted certificate.

    The official game certificate digest is reused from nonroot.NIANTIC_CERT_SHA256 so the installer
    validates the installed game against the same baseline the packager enforces.
    """
    def literal(value):
        # json.dumps emits a valid Java double-quoted string literal for ASCII values.
        return json.dumps(str(value))
    return ''.join([
        'package dev.pgrazor.root;\n',
        '/** Generated by rooted_installer.build_installer; do not edit or check in. */\n',
        'final class InstallerConfig {\n',
        '    private InstallerConfig() {}\n',
        '    static final String PGRAZOR_VERSION = ' + literal(version) + ';\n',
        '    static final String MODULE_ASSET = ' + literal(module_asset) + ';\n',
        '    static final String GAME_PACKAGE = ' + literal(target['package']) + ';\n',
        '    static final long GAME_VERSION_CODE = ' + str(int(target['versionCode'])) + 'L;\n',
        '    static final String GAME_VERSION_NAME = ' + literal(target.get('versionName', '')) + ';\n',
        '    static final String GAME_CERT_SHA256 = ' + literal(nonroot.NIANTIC_CERT_SHA256) + ';\n',
        '}\n',
    ])


def _manifest(version):
    """Installer manifest with the version substituted; the checked-in file carries placeholders."""
    text = (INSTALLER_DIR / 'AndroidManifest.xml').read_text(encoding='utf-8')
    text = re.sub(r'android:versionCode="[^"]*"',
                  'android:versionCode="%d"' % installer_version_code(version), text, count=1)
    text = re.sub(r'android:versionName="[^"]*"',
                  'android:versionName="%s"' % version.removeprefix('v'), text, count=1)
    return text


def compile_sources(target, version, folder, module_name):
    """Compile all installer entry points; source CI needs no module or signing key."""
    sources = sorted((INSTALLER_DIR / 'src').rglob('*.java'))
    if not sources:
        raise RuntimeError('Installer sources missing under ' + str(INSTALLER_DIR / 'src'))
    classes = Path(folder) / ('installer-compile-' + uuid.uuid4().hex[:12])
    classes.mkdir(parents=True)
    config = classes / 'InstallerConfig.java'
    config.write_text(_config_source(target, version, module_name), encoding='utf-8')
    build.run('javac', '-encoding', 'UTF-8', '-source', '8', '-target', '8',
              '-classpath', build.ANDROID, '-d', classes, config, *sources)
    for name in EXPECTED_CLASSES:
        if not (classes / 'dev/pgrazor/root' / (name + '.class')).is_file():
            raise RuntimeError('Installer compilation produced no ' + name + ' class')
    return classes


def build_installer(module_zip, target, version, folder):
    """Compiles, packages and signs the PGRazor Root installer APK; returns the signed APK Path.

    Parameters mirror what rooted.package() already has in scope:
      module_zip  the module zip Path (rooted.write_zip output) embedded under assets/<name>
      target      {'package','versionCode','versionName'} of the supported game (rooted's target)
      version     PGRazor version string (build.release_version output, e.g. 'v0.2.2')
      folder      the rooted build run folder; all intermediates and the APK are written here

    Integration call to add to rooted.package(), right after module_zip is written:

        import rooted_installer
        installer = rooted_installer.build_installer(module_zip, target, version, folder)
        report['installer'] = str(installer)
        report['installer_sha256'] = runtime_assets.sha256(installer)

    Uses build.TOOLS / build.ANDROID (the installed SDK) and build.signing_args() (the same key as
    the patched APK), so it inherits the project's offline javac/d8/aapt/apksigner tooling.
    """
    module_zip = Path(module_zip).resolve()
    folder = Path(folder).resolve()
    if not module_zip.is_file():
        raise FileNotFoundError('Module zip not found: ' + str(module_zip))
    version = 'v' + str(version).removeprefix('v')
    classes = compile_sources(target, version, folder, module_zip.name)

    jar = folder / 'installer-classes.jar'
    with zipfile.ZipFile(jar, 'w', zipfile.ZIP_DEFLATED) as out:
        for path in classes.rglob('*.class'):
            out.write(path, path.relative_to(classes).as_posix())
    dex_dir = folder / 'installer-dex'
    dex_dir.mkdir(exist_ok=True)
    build.run(build.TOOLS / 'd8.bat', '--min-api', '28', '--lib', build.ANDROID, '--output', dex_dir, jar)

    manifest_path = folder / 'installer-manifest' / 'AndroidManifest.xml'
    manifest_path.parent.mkdir(exist_ok=True)
    manifest_path.write_text(_manifest(version), encoding='utf-8')
    unsigned = folder / 'installer-unsigned.apk'
    build.run(build.TOOLS / 'aapt.exe', 'package', '-f', '-M', manifest_path,
              '-S', INSTALLER_DIR / 'res', '-I', build.ANDROID, '-F', unsigned)
    with zipfile.ZipFile(unsigned, 'a', zipfile.ZIP_DEFLATED) as out:
        out.write(dex_dir / 'classes.dex', 'classes.dex')
        # Already a compressed zip; store it so the APK is not needlessly recompressed.
        out.write(module_zip, 'assets/' + module_zip.name, compress_type=zipfile.ZIP_STORED)

    aligned = folder / 'installer-aligned.apk'
    build.run(build.TOOLS / 'zipalign.exe', '-f', '4', unsigned, aligned)
    apk = folder / ('PGRazor-Root-' + version + '.apk')
    build.run(build.TOOLS / 'apksigner.bat', 'sign', *build.signing_args(), '--out', apk, aligned)
    build.run(build.TOOLS / 'apksigner.bat', 'verify', apk)
    print('Installer APK:', apk, flush=True)
    return apk


def main(argv=None):
    """Standalone build from an existing rooted-run report.json (has module, target, version)."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('report', type=Path, nargs='?', help='report.json from a rooted.py run')
    parser.add_argument('--check', action='store_true', help='Compile installer sources without packaging or signing')
    args = parser.parse_args(argv)
    if args.check:
        if args.report:
            parser.error('--check does not take a build report')
        import tempfile
        schema = ROOT / 'native/schema/game'
        profile = json.loads((schema / json.loads((schema / 'current.json').read_text())['profile']).read_text())
        target = {'package': 'com.nianticlabs.pokemongo', 'versionCode': profile['version_code'],
                  'versionName': profile['game_version']}
        with tempfile.TemporaryDirectory(prefix='pgrazor-installer-check-') as folder:
            compile_sources(target, build.release_version(ROOT), folder, 'PGRazor-Root-module.zip')
        return
    if not args.report:
        parser.error('report is required unless --check is supplied')
    report = json.loads(args.report.read_text(encoding='utf-8'))
    build_installer(Path(report['module']), report['target'], report['version'], args.report.resolve().parent)


if __name__ == '__main__':
    main()
